-- 目标：把 history.json 的文件式存储迁移到关系库（多实例 / 大历史 / 后台复用）。
-- 方言：以 SQLite 语法书写（AUTOINCREMENT）；PostgreSQL 映射见各表注释与文末。
-- 驱动由调用方注入（database/sql），本文件不创建连接、不依赖任何第三方库。
--
-- 应用方式（Go，接线点）：
--     db, _ := sql.Open(driverName, dsn)          // 调用方注入 driver
--     if err := store.ApplyMigrations(db); err != nil { ... }   // 幂等 DDL
--     st := store.NewSQLStore(db)                 // 默认 SQLite 方言
--     // PostgreSQL：store.NewSQLStoreDialect(db, store.DialectPostgres)
--
-- 幂等：所有 DDL 使用 IF NOT EXISTS，可重复执行；数据迁移（history.json → SQL）
-- 由 store.MigrateFromJSON 负责（事务 + ON CONFLICT DO NOTHING）。
--
-- 版本：单个文件对应一个版本号（文件名前缀），如需演进请新增 002_*.sql，
-- 不要修改已发布的 001（改历史迁移会让已部署库不可复现）。
