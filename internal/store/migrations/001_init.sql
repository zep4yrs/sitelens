-- -----------------------------------------------------------------------------
-- scans：扫描记录（字段与 store.ScanRecord 对齐；result_json 保存完整
-- engine.Result，与 JSON 版 history.json 的 result 字段同构，可无损回放/导出）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS scans (
  id           INTEGER     PRIMARY KEY AUTOINCREMENT, -- 历史 id（迁移时原样保留，保证深链不断）
  url          TEXT        NOT NULL DEFAULT '',
  host         TEXT        NOT NULL DEFAULT '',
  title        TEXT        NOT NULL DEFAULT '',
  status       INTEGER     NOT NULL DEFAULT 0,        -- HTTP 状态码（采集失败为 0）
  grade        TEXT        NOT NULL DEFAULT '',       -- security_grade（对齐 ScanSummary）
  score        INTEGER     NOT NULL DEFAULT 0,        -- security_score
  scanned_at   TEXT        NOT NULL DEFAULT '',       -- 扫描时间串（保持与 JSON 版一致的展示格式）
  result_json  TEXT,                                  -- engine.Result JSON（NULL = 无结果/中断）
  options_json TEXT                                   -- 扫描选项 JSON（NULL = 未记录）
);
-- PostgreSQL：id 改为 BIGINT GENERATED BY DEFAULT AS IDENTITY（或 BIGSERIAL）；
-- 其余类型不变（TEXT/INTEGER 通用）。列表按 id 倒序（新→旧）。

CREATE INDEX IF NOT EXISTS idx_scans_host ON scans (host);
CREATE INDEX IF NOT EXISTS idx_scans_scanned_at ON scans (scanned_at);

-- -----------------------------------------------------------------------------
-- triage：CP-08 人工复核（误报 / 确认 / 忽略）。主键 = scan_id + fingerprint，
-- 与 JSON 版 <dataDir>/triage.json 索引语义一致；fingerprint 口径见
-- store.TriageEntry 与 internal/server/batchdiff.go（同源 SARIF 指纹）。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS triage (
  scan_id     INTEGER NOT NULL,
  fingerprint TEXT    NOT NULL,
  verdict     TEXT    NOT NULL,                       -- false_positive / confirmed / ignored
  note        TEXT,
  updated_at  TEXT    NOT NULL DEFAULT '',            -- RFC3339（UTC）
  PRIMARY KEY (scan_id, fingerprint)
);

CREATE INDEX IF NOT EXISTS idx_triage_verdict ON triage (verdict);

-- -----------------------------------------------------------------------------
-- whitelist：CP-08 白名单。host 支持精确域名或 "*.example.com"（不含 apex）；
-- rule_id 为规则 id，"*" 表示该 host 下所有规则。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS whitelist (
  host       TEXT NOT NULL,
  rule_id    TEXT NOT NULL,
  reason     TEXT,
  created_at TEXT NOT NULL DEFAULT '',                -- RFC3339（UTC）
  PRIMARY KEY (host, rule_id)
);

CREATE INDEX IF NOT EXISTS idx_whitelist_rule ON whitelist (rule_id);

