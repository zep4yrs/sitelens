// 生产数据库驱动注册回归：默认构建必须真正带 sqlite（modernc）与 pgx stdlib，
// 否则 store.driver=sqlite|postgres 会 unknown driver 并静默回退 JSON。
package store

import (
	"database/sql"
	"path/filepath"
	"strings"
	"testing"

	"cnb.cool/feng-qiao/sitelens/internal/engine"
)

func TestProductionSQLDriversRegistered(t *testing.T) {
	have := map[string]bool{}
	for _, d := range sql.Drivers() {
		have[d] = true
	}
	for _, want := range []string{"sqlite", "pgx"} {
		if !have[want] {
			t.Fatalf("生产驱动 %q 未注册；已注册: %v", want, sql.Drivers())
		}
	}
}

func TestSQLiteDriverEndToEnd(t *testing.T) {
	dsn := "file:" + filepath.Join(t.TempDir(), "e2e.db") + "?_pragma=busy_timeout(5000)"
	db, err := sql.Open("sqlite", dsn)
	if err != nil {
		t.Fatalf("sql.Open(sqlite): %v", err)
	}
	defer db.Close()

	if err := ApplyMigrations(db); err != nil {
		t.Fatalf("ApplyMigrations: %v", err)
	}
	// 幂等：重复执行不应报错
	if err := ApplyMigrations(db); err != nil {
		t.Fatalf("ApplyMigrations 幂等失败: %v", err)
	}

	st := NewSQLStoreDialect(db, DialectSQLite)
	id, err := st.SaveScan(&engine.Result{
		URL: "https://e2e.example", Host: "e2e.example", ScannedAt: "2026-01-01 00:00:00",
	}, nil)
	if err != nil {
		t.Fatalf("SaveScan: %v", err)
	}
	if id != 1 {
		t.Fatalf("SaveScan id = %d, want 1", id)
	}
	rec, err := st.GetScan(id)
	if err != nil || rec == nil || rec.Host != "e2e.example" {
		t.Fatalf("GetScan = %+v, err=%v", rec, err)
	}
	sums, err := st.ListScans(10, "")
	if err != nil || len(sums) != 1 || sums[0].Host != "e2e.example" {
		t.Fatalf("ListScans = %+v, err=%v", sums, err)
	}
	if n, err := st.CountScans(); err != nil || n != 1 {
		t.Fatalf("CountScans = %d, err=%v", n, err)
	}
	if ok, err := st.DeleteScan(id); err != nil || !ok {
		t.Fatalf("DeleteScan = %v, err=%v", ok, err)
	}
}

// PostgreSQL 迁移 DDL：SQLite 语法里的自增主键必须转成 IDENTITY，其余保持；
// SQLite 方言不得改写原文。
func TestPostgresMigrationDDL(t *testing.T) {
	files, err := MigrationFiles()
	if err != nil || len(files) == 0 {
		t.Fatalf("MigrationFiles: %v (n=%d)", err, len(files))
	}
	foundIdentity := false
	for _, f := range files {
		for _, stmt := range f.Statements {
			pg := migrationStatementForDialect(stmt, DialectPostgres)
			if strings.Contains(strings.ToUpper(pg), "AUTOINCREMENT") {
				t.Fatalf("PG DDL 仍含 AUTOINCREMENT: %s", pg)
			}
			if strings.Contains(pg, "GENERATED BY DEFAULT AS IDENTITY") {
				foundIdentity = true
			}
			if sqlite := migrationStatementForDialect(stmt, DialectSQLite); sqlite != stmt {
				t.Fatalf("SQLite DDL 不应被改写: %s", sqlite)
			}
		}
	}
	if !foundIdentity {
		t.Fatal("PG DDL 未生成 IDENTITY 主键")
	}
}
